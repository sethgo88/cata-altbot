#!/usr/bin/env python3
"""
scaffold-strategy.py — emit boilerplate src/strategies/{Spec}Strategy.{h,cpp}.

Phase 5 onboarding tool. Copies the structural skeleton (class declaration,
ResolveSpellCache, TryCast / IsOnCooldown, DoMaintenance / DoDefensives,
Update() with cast-in-progress + GCD guards) used by the 4 existing
strategies, with TODO markers where the per-spec rotation tier methods go.

Inputs (CLI flags, all required):
  --class      class slug (e.g. WARLOCK, MAGE, PALADIN)
  --tree       TalentTab.dbc ID for this spec (verify via WDBXEditor)
  --slug       file slug (e.g. demonology-warlock, holy-paladin)
  --role       healer | ranged-dps | melee-dps | tank
  --filler     primary GCD-bucket spell name for the filler/probe (e.g. "Shadow Bolt")

Outputs:
  src/strategies/{ClassName}Strategy.{h,cpp}
  diff snippet for AltbotStrategyFactory.cpp printed to stdout
  checklist of follow-up steps printed to stdout

Re-run is safe — files are overwritten only after a confirmation prompt.
"""
import argparse
