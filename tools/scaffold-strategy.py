def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--class",       required=True, dest="cls",
                   help="Class name slug (e.g. WARLOCK, MAGE, PRIEST)")
    p.add_argument("--tree",        required=True, type=int,
                   help="TalentTab.dbc ID for this spec")
    p.add_argument("--slug",        required=True,
                   help="File slug (e.g. demonology-warlock, holy-paladin)")
    p.add_argument("--role",        required=True,
                   choices=["healer", "ranged-dps", "melee-dps", "tank"])
    p.add_argument("--filler",      required=True,
                   help="Primary filler/probe spell name (used by GCD probe)")
    p.add_argument("--force",       action="store_true",
                   help="Overwrite existing files without prompting")
    args = p.parse_args()

    classname  = CLASSNAME_FROM_SLUG(args.slug)
    spec_label = SPEC_LABEL_FROM_SLUG(args.slug)
    tree_const = args.slug.split("-")[0].upper()    # affliction-warlock -> AFFLICTION

    h_path   = STRAT_DIR / f"{classname}.h"
    cpp_path = STRAT_DIR / f"{classname}.cpp"

    for path in (h_path, cpp_path):
        if path.exists() and not args.force:
            raise SystemExit(f"refusing to overwrite existing {path} (pass --force)")

    STRAT_DIR.mkdir(parents=True, exist_ok=True)

    h_path.write_text(H_TEMPLATE.substitute(
        classname=classname, slug=args.slug))
    cpp_path.write_text(CPP_TEMPLATE.substitute(
        classname=classname, slug=args.slug, role=args.role,
        spec_label=spec_label, filler=args.filler))

    print(f"  wrote {h_path}")
    print(f"  wrote {cpp_path}")
    print()
    print(FACTORY_DIFF_TEMPLATE.substitute(
        classname=classname, slug=args.slug,
        class_const=tree_const, class_upper=args.cls.upper(),
        tree_const="TREE", tree_id=args.tree))
    print(CHECKLIST_TEMPLATE.substitute(
        classname=classname, slug=args.slug, tree_id=args.tree))

if __name__ == "__main__":
    main()
