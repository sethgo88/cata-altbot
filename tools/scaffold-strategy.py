import string
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
STRAT_DIR = REPO_ROOT / "src" / "strategies"

CLASSNAME_FROM_SLUG = lambda slug: "".join(p.capitalize() for p in re.split(r"[-_]+", slug)) + "Strategy"
SPEC_LABEL_FROM_SLUG = lambda slug: "".join(p.capitalize() for p in re.split(r"[-_]+", slug))

# ---- header template ----
H_TEMPLATE = string.Template(r"""#pragma once
#include "AltbotStrategy.h"
#include <array>
#include <cstdint>

class Player;
class Unit;

// $classname — TODO(rotation): autogenerated scaffold by tools/scaffold-strategy.py.
//
// Replace the Spell enum and tier methods with the spec rotation per
// docs/specs/$slug.md. See FrostMageStrategy / MmHunterStrategy / etc. for
// reference patterns. The cast pipeline gotchas in CLAUDE.md (passive talent
// name collisions, cast-in-progress + GCD guards, every cast through
// CastWithLog) all apply here.
class $classname : public AltbotStrategy
{
public:
    $classname() = default;

    void         Update(Player* bot, Player* master, AltbotTickContext const& ctx) override;
    char const*  GetName() const override { return "$slug"; }

    void InvalidateCache() { _cacheResolved = false; _cache.fill(0); }

private:
    enum class Spell : uint8_t
    {
        // TODO(rotation): list every spell the rotation references.
        // The Filler entry is required — the ctor uses its cooldown info
        // for the post-cast GCD probe in Update().
        Filler = 0,
        Count
    };

    std::array<uint32, size_t(Spell::Count)> _cache{};
    bool _cacheResolved = false;

    uint32 GetSpell(Spell s) const { return _cache[size_t(s)]; }
    void   ResolveSpellCache(Player* bot);

    bool TryCast(Player* bot, Unit* target, Spell s) const;
    bool IsOnCooldown(Player* bot, uint32 spellId) const;

    void DoMaintenance(Player* bot);
    bool DoDefensives(Player* bot);

    // TODO(rotation): one Tier_X per priority slot.
};
""")

# ---- cpp template ----
CPP_TEMPLATE = string.Template(r"""#include "$classname.h"
#include "AltbotCombatLog.h"
#include "AltbotPosition.h"
#include "AltbotPositionManager.h"
#include "AltbotTickContext.h"
#include "Log.h"
#include "Player.h"
#include "SpellHistory.h"
#include "SpellInfo.h"
#include "SpellMgr.h"
#include "Unit.h"
#include "strategies/StrategyUtil.h"

namespace
{
    constexpr char const* SPEC_LABEL = "$spec_label";

    // TODO(rotation): per-spec constants here (HP gates, range cutoffs, etc.).
    constexpr float DESIRED_RANGE_Y = 25.0f;
    constexpr uint32 ROTATION_THREAT_WINDOW_MS = 2000;
}

void $classname::Update(Player* bot, Player* master, AltbotTickContext const& ctx)
{
    if (!bot || !master || !bot->IsAlive())
        return;

    Unit* target = master->GetSelectedUnit();
    if (!target || !target->IsAlive())
        return;

    if (!_cacheResolved)
    {
        ResolveSpellCache(bot);
        _cacheResolved = true;
    }

    DoMaintenance(bot);

    if (DoDefensives(bot))
        return;

    // Cast pipeline gotcha 3: skip the rotation while a cast is in progress
    // (channels covered by IsNonMeleeSpellCast(false), regular casts by
    // UNIT_STATE_CASTING). Without this every long cast gets re-issued each
    // tick and fails with SPELL_FAILED_SPELL_IN_PROGRESS.
    if (bot->HasUnitState(UNIT_STATE_CASTING) || bot->IsNonMeleeSpellCast(false))
        return;

    // Cast pipeline gotcha 4: skip the rotation while the GCD is active.
    // GCD is invisible to IsCasting; HasGlobalCooldown is keyed by
    // StartRecoveryCategory so any standard-bucket spell works as the probe.
    if (uint32 fillerId = GetSpell(Spell::Filler))
    {
        SpellInfo const* fillerInfo = sSpellMgr->GetSpellInfo(fillerId);
        if (fillerInfo && bot->GetSpellHistory()->HasGlobalCooldown(fillerInfo))
            return;
    }

    // Threat-window gate: $role-aware DPS waits 2s for the tank to settle
    // threat before opening the rotation. Healers / pet-tanks override.
    if (ctx.combatElapsedMs < ROTATION_THREAT_WINDOW_MS && ctx.InInstance())
        return;

    // Maintain caster range when applicable. Healers should *not* call this —
    // they stay near master / party for AoE-heal radius. Melee specs delete.
    if (ctx.positionManager)
        ctx.positionManager->SetIntent(
            AltbotPositionManager::MakeRangedDpsIntent(target, master));

    // TODO(rotation): tier dispatch. Set tier metadata before each Tier_X
    // check so the AltbotCombatLog telemetry can attribute the cast:
    //
    //   AltbotCombatLog::SetCurrentTier(0, "TierName");
    //   if (Tier_Foo(bot, target)) return;
    //
    AltbotCombatLog::OnNoTierFired(bot, SPEC_LABEL);
}

void $classname::ResolveSpellCache(Player* bot)
{
    _cache.fill(0);
    auto find = [bot](char const* name) {
        return StrategyUtil::FindSpellByFamilyName(bot, /*TODO: SPELLFAMILY_X*/ 0, name);
    };
    // TODO(rotation): _cache[size_t(Spell::Filler)] = find("$filler");
    (void)find;
    TC_LOG_INFO("altbot", "%s[%s] cache resolved", SPEC_LABEL, bot->GetName().c_str());
}

bool $classname::TryCast(Player* bot, Unit* target, Spell s) const
{
    uint32 id = GetSpell(s);
    if (!id || !target)
        return false;
    SpellInfo const* info = sSpellMgr->GetSpellInfo(id);
    if (!info || bot->GetSpellHistory()->HasCooldown(info))
        return false;
    return StrategyUtil::CastWithLog(bot, target, id, SPEC_LABEL) == SPELL_CAST_OK;
}

bool $classname::IsOnCooldown(Player* bot, uint32 spellId) const
{
    if (!spellId) return true;
    SpellInfo const* info = sSpellMgr->GetSpellInfo(spellId);
    if (!info) return true;
    return bot->GetSpellHistory()->HasCooldown(info);
}

void $classname::DoMaintenance(Player* /*bot*/)
{
    // TODO(rotation): armor / weapon imbue / aspect / aura maintenance.
}

bool $classname::DoDefensives(Player* /*bot*/)
{
    // TODO(rotation): emergency self-defenses (Ice Block, Soulburn, Deterrence,
    // displacement *only* when meleeNear>=2 && hp<60% — see CLAUDE.md gotcha #6).
    return false;
}
""")

